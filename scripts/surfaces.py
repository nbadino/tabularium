#!/usr/bin/env python3
"""Generated manifest of the model surfaces (program.md, phase P0).

Prints one row per model and one column per surface, read straight from the code:
the registries, the adapters and the settings. Nothing here is a second source of
truth, so nothing here can drift.

    python scripts/surfaces.py                 # markdown matrix
    python scripts/surfaces.py --verbose       # matrix + the reason of every cell
    python scripts/surfaces.py --json          # machine-readable
    python scripts/surfaces.py --check         # exit 1 if a surface is missing

`--check` is what CI runs and what `AGENTS.md` points at: it is the cheap proof that
a model is complete across the whole application, not only in the file that changed.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

# Importing the registries must not touch the user's data folder or open the real
# database: this script is an inspection tool, not a product entry point.
os.environ.setdefault("TABULARIUM_AUTH", "off")
if not os.environ.get("TABULARIUM_ROOT"):
    os.environ["TABULARIUM_ROOT"] = tempfile.mkdtemp(prefix="tabularium-surfaces-")

from app.services import model_adapters, model_surface  # noqa: E402

MARKS = {"declared": "✓", "not_applicable": "○", "missing": "✗"}


def _rows() -> list[model_surface.ModelRow]:
    return sorted(model_surface.matrix(), key=lambda row: row.adapter_id)


def _markdown(rows: list[model_surface.ModelRow]) -> str:
    columns = model_surface.SURFACES + ("prefill", "cloud")
    head = "| Model | " + " | ".join(columns) + " |"
    sep = "|---|" + "".join(":-:|" for _ in columns)
    lines = [
        "# Model surfaces",
        "",
        "_Generated by `scripts/surfaces.py` — do not edit by hand._",
        "",
        head,
        sep,
    ]
    for row in rows:
        cells = [MARKS[row.state(surface).state] for surface in model_surface.SURFACES]
        adapter = model_adapters.get_adapter(row.adapter_id)
        mode = getattr(adapter, "native_prefill_mode", None)
        runner = getattr(adapter, "native_runner", None)
        cells.append(f"{mode} ({runner})" if mode and runner else (mode or "—"))
        cells.append(row.cloud_template or "—")
        lines.append(f"| {row.display_name} (`{row.adapter_id}`) | " + " | ".join(cells) + " |")
    lines += [
        "",
        "`✓` declared · `○` not applicable, with a declared reason · `✗` missing",
        "",
    ]
    return "\n".join(lines)


def _reasons(rows: list[model_surface.ModelRow]) -> str:
    lines = ["", "## Why each cell is what it is", ""]
    for row in rows:
        lines.append(f"**{row.adapter_id}**")
        for surface in model_surface.SURFACES:
            cell = row.state(surface)
            lines.append(f"- `{surface}`: {cell.state} — {cell.reason}")
        lines.append("")
    return "\n".join(lines)


def _json(rows: list[model_surface.ModelRow]) -> str:
    payload = [
        {
            "adapter_id": row.adapter_id,
            "display_name": row.display_name,
            "cloud_template": row.cloud_template,
            "surfaces": {
                surface: {"state": row.state(surface).state, "reason": row.state(surface).reason}
                for surface in model_surface.SURFACES
            },
        }
        for row in rows
    ]
    return json.dumps(payload, indent=2, ensure_ascii=False)


def _check(rows: list[model_surface.ModelRow]) -> int:
    problems = [
        f"{row.adapter_id}.{surface}: {row.state(surface).reason}"
        for row in rows
        for surface in model_surface.SURFACES
        if row.state(surface).state == "missing"
    ]
    problems += model_surface.vocabulary_violations() + model_surface.stale_excuses()
    if problems:
        print("model surfaces are incomplete:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        print(
            "\nDeclare the missing surface, or declare the model as legitimately without "
            "it (see app/services/model_surface.py).",
            file=sys.stderr,
        )
        return 1
    print(f"model surfaces: {len(rows)} models, all required surfaces declared")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--verbose", action="store_true", help="print the reason of every cell")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    parser.add_argument("--check", action="store_true", help="exit 1 if a surface is missing")
    parser.add_argument(
        "--write", metavar="PATH",
        help="write the markdown matrix to a file (generated: never edit it by hand)",
    )
    args = parser.parse_args(argv)

    rows = _rows()
    if args.check:
        return _check(rows)
    if args.json:
        print(_json(rows))
        return 0
    if args.write:
        target = Path(args.write)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(_markdown(rows), encoding="utf-8")
        print(f"wrote {target} ({len(rows)} models)")
        return 0
    print(_markdown(rows))
    if args.verbose:
        print(_reasons(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
