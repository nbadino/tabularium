# Setup ambiente backend su Windows (PowerShell): venv + dipendenze.
$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..\backend")
$py = if ($env:PYTHON) { $env:PYTHON } else { "python" }
$pyVersion = (& $py -c "import sys; print(f'{sys.version_info[0]}.{sys.version_info[1]}')").Trim()
if ($LASTEXITCODE -ne 0) {
    throw "Python non trovato: $py (imposta PYTHON sul percorso di Python 3.11, 3.12 o 3.13)"
}
if ($pyVersion -notin @("3.11", "3.12", "3.13")) {
    throw "Versione Python non supportata: $pyVersion (richiesta 3.11–3.13)"
}

if (-not (Test-Path ".venv")) {
    Write-Host ">> Creo virtualenv..."
    & $py -m venv .venv
}
& ".venv\Scripts\python.exe" -m pip install --upgrade pip -q
& ".venv\Scripts\python.exe" -m pip install -r requirements.txt -r requirements-dev.txt
& ".venv\Scripts\python.exe" -c "import cryptography; print('cryptography ' + cryptography.__version__)"
if ($LASTEXITCODE -ne 0) {
    throw "Dipendenza cryptography non disponibile: il vault dei segreti non è sicuro."
}
# Encrypts the credentials saved from the UI, as setup_backend.sh does. It lives in
# .env, never in the database next to the ciphertext, and is never regenerated.
$envFile = Join-Path $PSScriptRoot "..\.env"
if (-not ((Test-Path $envFile) -and (Select-String -Path $envFile -Pattern '^TABULARIUM_VAULT_KEY=' -Quiet))) {
    $key = (& ".venv\Scripts\python.exe" -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())").Trim()
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    Add-Content -Path $envFile -Encoding utf8 -Value "`n# Encrypts provider credentials saved from the UI (generated by setup_backend.ps1).`nTABULARIUM_VAULT_KEY=$key"
    Write-Host ">> Generata TABULARIUM_VAULT_KEY in .env"
}
Write-Host ">> Backend pronto."
